"""Copy the files of the edition named in config.json to where the tools read them.

GitHub runs workflows only from ``.github/workflows/`` and the Databricks CLI
reads only a root ``databricks.yml``, so the per-edition sources under
``cicd/`` are copied there (with a "generated" header) and committed.

    uv run python cicd/apply_edition.py            # apply
    uv run python cicd/apply_edition.py --check    # exit 1 if generated files differ
"""

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def header(root: Path, source: Path) -> str:
    return f"# GENERATED by cicd/apply_edition.py from {source.relative_to(root).as_posix()} -- edit the source, not this file.\n"


def planned_files(root: Path, edition: str) -> dict[Path, str]:
    """Return {destination: content} for the edition, relative to ``root``."""
    sources = {root / "databricks.yml": root / "cicd" / "databricks" / f"{edition}.yml"}
    for source in sorted((root / "cicd" / "workflows" / edition).glob("*.yml")):
        sources[root / ".github" / "workflows" / source.name] = source
    return {
        dest: header(root, source) + source.read_text(encoding="utf-8").replace("\r\n", "\n")
        for dest, source in sources.items()
    }


def stale_workflows(root: Path, planned: dict[Path, str]) -> list[Path]:
    return [p for p in (root / ".github" / "workflows").glob("*.yml") if p not in planned]


def differing(root: Path, planned: dict[Path, str]) -> list[Path]:
    def current(path: Path) -> str | None:
        return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None

    drift = [dest for dest, content in planned.items() if current(dest) != content]
    return drift + stale_workflows(root, planned)


def target_mismatch(root: Path, environments: list[str]) -> set[str]:
    bundle = yaml.safe_load((root / "databricks.yml").read_text(encoding="utf-8"))
    return set(bundle["targets"]) ^ set(environments)


def apply(root: Path, planned: dict[Path, str]) -> None:
    for stale in stale_workflows(root, planned):
        stale.unlink()
    for dest, content in planned.items():
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing when files differ")
    check = parser.parse_args().check

    config = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))
    planned = planned_files(ROOT, config["edition"])
    if not check:
        apply(ROOT, planned)
    drift = differing(ROOT, planned)
    mismatch = target_mismatch(ROOT, config["environments"])
    for path in drift:
        print(f"differs from edition '{config['edition']}': {path.relative_to(ROOT).as_posix()}")
    if mismatch:
        print(f"bundle targets differ from config.json environments: {sorted(mismatch)}")
    return 1 if drift or mismatch else 0


if __name__ == "__main__":
    sys.exit(main())
