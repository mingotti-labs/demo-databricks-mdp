"""Tests for cicd/apply_edition.py, one group per scenario of the edition-config spec."""

from apply_edition import apply, differing, planned_files, target_mismatch


def make_repo(root):
    files = {
        "cicd/databricks/free.yml": "targets:\n  dev: {}\n  prd: {}\n",
        "cicd/databricks/standard.yml": "targets:\n  dev: {}\n  tst: {}\n  prd: {}\n",
        "cicd/workflows/free/main.yml": "name: free-main\n",
        "cicd/workflows/standard/main.yml": "name: standard-main\n",
        "cicd/workflows/standard/pr.yml": "name: pr\n",
        ".github/workflows/old.yml": "name: old\n",
    }
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def test_switching_edition_copies_that_editions_files(tmp_path):
    make_repo(tmp_path)
    apply(tmp_path, planned_files(tmp_path, "free"))
    assert "free-main" in (tmp_path / ".github/workflows/main.yml").read_text()
    assert "tst" not in (tmp_path / "databricks.yml").read_text()
    assert not (tmp_path / ".github/workflows/old.yml").exists()
    assert not (tmp_path / ".github/workflows/pr.yml").exists()


def test_generated_files_carry_a_header(tmp_path):
    make_repo(tmp_path)
    planned = planned_files(tmp_path, "standard")
    assert planned[tmp_path / "databricks.yml"].startswith("# GENERATED by cicd/apply_edition.py")


def test_clean_repo_has_no_drift(tmp_path):
    make_repo(tmp_path)
    planned = planned_files(tmp_path, "free")
    apply(tmp_path, planned)
    assert differing(tmp_path, planned) == []


def test_hand_edit_of_a_generated_file_is_drift(tmp_path):
    make_repo(tmp_path)
    planned = planned_files(tmp_path, "free")
    apply(tmp_path, planned)
    edited = tmp_path / "databricks.yml"
    edited.write_text(edited.read_text() + "extra: 1\n")
    assert differing(tmp_path, planned) == [edited]


def test_bundle_targets_must_match_environments(tmp_path):
    make_repo(tmp_path)
    apply(tmp_path, planned_files(tmp_path, "free"))
    assert target_mismatch(tmp_path, ["dev", "prd"]) == set()
    assert target_mismatch(tmp_path, ["dev", "tst", "prd"]) == {"tst"}
